export function isLocale(value: string | null | undefined): value is Locale {
  return SUPPORTED_LOCALES.includes((value ?? '') as Locale);
}

export function getDirection(locale: Locale): 'ltr' | 'rtl' {
  return RTL_LOCALES.includes(locale) ? 'rtl' : 'ltr';
}

type TranslationParams = Record<string, string | number>;

export function createTranslator(locale: Locale) {
  return (key: string, params?: TranslationParams) => {
    const localized = TRANSLATIONS[locale][key];
    const defaultLocalized = TRANSLATIONS[DEFAULT_LOCALE][key];
    const template =
      localized ??
      (locale === SOURCE_LOCALE ? key : defaultLocalized ?? key);

    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (_, token: string) => String(params[token] ?? `{${token}}`));
  };
}

export function formatDateTime(locale: Locale, value: string | number | Date) {
  return new Intl.DateTimeFormat(LOCALE_TO_INTL_LANG[locale], {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(value));
}

export function formatNumber(locale: Locale, value: number) {
  return new Intl.NumberFormat(LOCALE_TO_INTL_LANG[locale]).format(value);
}
